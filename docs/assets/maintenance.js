const portalUrl = "https://portal.stacloud.eu.cc/";
const redirectAt = Date.now() + 30_000;
const clock = document.querySelector("#clock");
const portalStatus = document.querySelector("#portal-check-status");
let currentLanguage = "vi";
let redirectStarted = false;

function savedLanguage() {
  try {
    return window.localStorage.getItem("stacloud-language");
  } catch {
    return null;
  }
}

function setLanguage(language) {
  currentLanguage = language === "en" ? "en" : "vi";
  const copy = translations[currentLanguage];
  document.documentElement.lang = currentLanguage;
  document.title = copy.pageTitle;
  document.querySelector('meta[name="description"]').content = copy.pageDescription;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = copy[element.dataset.i18n];
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    element.setAttribute("aria-label", copy[element.dataset.i18nAria]);
  });
  document.querySelectorAll("[data-i18n-data-label]").forEach((element) => {
    element.dataset.label = copy[element.dataset.i18nDataLabel];
  });
  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.lang === currentLanguage));
  });

  updateClock();
  try {
    window.localStorage.setItem("stacloud-language", currentLanguage);
  } catch {
    // Switching languages still works when storage is disabled.
  }
}

function updateClock() {
  const locale = currentLanguage === "vi" ? "vi-VN" : "en-US";
  const time = new Intl.DateTimeFormat(locale, {
    dateStyle: "medium",
    timeStyle: "medium"
  }).format(new Date());
  clock.textContent = `${translations[currentLanguage].clockPrefix} ${time}`;
}

function updateCountdown() {
  const remaining = Math.max(0, Math.ceil((redirectAt - Date.now()) / 1000));
  document.querySelectorAll("[data-portal-countdown]").forEach((element) => {
    element.textContent = String(remaining);
  });
  if (remaining === 0) redirectToPortal();
}

function redirectToPortal() {
  if (redirectStarted) return;
  redirectStarted = true;
  window.clearInterval(tickInterval);
  if (portalStatus) {
    portalStatus.setAttribute("aria-live", "polite");
    portalStatus.textContent = translations[currentLanguage].redirecting;
  }
  window.location.assign(portalUrl);
}

document.querySelectorAll("[data-lang]").forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
});

const preferredLanguage = savedLanguage() || (navigator.language.toLowerCase().startsWith("vi") ? "vi" : "en");
setLanguage(preferredLanguage);
updateCountdown();
const tickInterval = window.setInterval(() => {
  updateCountdown();
  updateClock();
}, 1000);
window.setTimeout(redirectToPortal, 30_000);
